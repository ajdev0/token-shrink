export interface McpServerOptions {
  /**
   * Project root to watch. When omitted (and the `ROOT` env var is unset) the
   * server runs in auto-detect mode: it locates the project from markers
   * around the process cwd if possible, otherwise lazily from the first tool
   * call's `activeFilePath`.
   */
  root?: string;
  /** Extra ignore globs for the watcher. */
  ignored?: Matcher[];
  /** Silence log output (stdio must stay clean for the MCP protocol). */
  silent?: boolean;
  /** Whether to auto-write agent integration rules at all. Default true. */
  createRule?: boolean;
  /** Which agent rule target(s) to write. Default all. */
  ruleTarget?: RuleTarget | RuleTarget[];
  /**
   * Persist per-call token savings to `<root>/.token-shrink/stats.json`
   * (read by `token-shrink stats` and the status line). Default true.
   */
  recordStats?: boolean;
}

export interface RuleWriteResult {
  created: boolean;
  skipped: 'none' | 'exists' | 'user';
  /** Path of the rule file that was considered. */
  filePath: string;
}

/**
 * Write a rules file for a given agent target. Idempotent and version-aware:
 *   - absent -> create it (tagged with our sentinel + version marker);
 *   - has our sentinel AND current version marker -> skip (already ours);
 *   - has our sentinel but predates the version marker -> rewrite (upgrade);
 *   - present without our sentinel -> leave the user's file untouched.
 */
export function createAutoRule(root: string, target: RuleTarget): RuleWriteResult {
  const spec = ruleTargets[target];
  const rulePath = path.join(root, spec.relPath);
  // `.tokenshrinkrc.json` "autoWorkflow": false switches to lightweight rules.
  const autoWorkflow = loadConfig(root).autoWorkflow !== false;
  const body = autoWorkflow
    ? spec.body
    : spec.body.replace(WORKFLOW_GUIDANCE, LIGHT_GUIDANCE);
  try {
    if (fs.existsSync(rulePath)) {
      const existing = fs.readFileSync(rulePath, 'utf8');
      if (existing.includes(spec.sentinel)) {
        if (existing.includes(RULE_VERSION_MARKER)) {
          return { created: false, skipped: 'exists', filePath: rulePath };
        }
        // Legacy rule we wrote before the version marker existed: upgrade it.
        fs.writeFileSync(rulePath, body, 'utf8');
        return { created: true, skipped: 'none', filePath: rulePath };
      }
      return { created: false, skipped: 'user', filePath: rulePath };
    }
    fs.mkdirSync(path.dirname(rulePath), { recursive: true });
    fs.writeFileSync(rulePath, body, 'utf8');
    return { created: true, skipped: 'none', filePath: rulePath };
  } catch (err) {
    // Never let a rule-write failure take down the MCP server; surface via result.
    process.stderr.write(
      `[token-shrink] Failed to write rule for "${target}": ${(err as Error).message}\n`,
    );
    return { created: false, skipped: 'none', filePath: rulePath };
  }
}

/** Back-compat alias for code that imported the old Cursor-only helper. */
export function createCursorRule(root: string): RuleWriteResult {
  return createAutoRule(root, 'cursor');
}

/** Expand `ruleTarget` (single / array / all) into the ordered list to write. */
function resolveTargets(ruleTarget: McpServerOptions['ruleTarget']): RuleTarget[] {
  if (!ruleTarget) return ['cursor', 'claude', 'cline'];
  const list = Array.isArray(ruleTarget) ? ruleTarget : [ruleTarget];
  if (list.includes('all' as unknown as RuleTarget)) return ['cursor', 'claude', 'cline'];
  return list;
}

/** Is `child` inside (or equal to) directory `parent`? */
function isWithin(parent: string, child: string): boolean {
  const rel = path.relative(path.resolve(parent), path.resolve(child));
  return rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
}

/**
 * Normalize the single-file / multi-file active-file inputs into a path list.
 * Exactly one of the two forms may be supplied.
 */
function resolveActiveFiles(
  single: string | undefined,
  many: string[] | undefined,
): string[] {
  if (many && many.length > 0) {
    if (single) {
      throw new Error('Pass either `activeFilePath` or `activeFiles`, not both.');
    }
    return many;
  }
  if (single) return [single];
  throw new Error('`activeFilePath` or `activeFiles` is required');
}

/**
 * Start the MCP server. Because the MCP protocol runs over stdio, all human
 * logging should go to stderr; stdout is reserved for JSON-RPC.
 */
export async function startMcpServer(opts: McpServerOptions = {}): Promise<McpServer> {
  const log = (msg: string) => {
    if (!opts.silent) process.stderr.write(`[token-shrink] ${msg}\n`);
  };
  const textReply = (text: string) => ({
    content: [{ type: 'text' as const, text }],
  });
  // Show the user what a call saved (yellow on stderr) and persist it for
  // `token-shrink stats` / the Claude Code status line.
  const sessionStartedAt = new Date().toISOString();
  const reportSavings = (tool: string, s: Savings) => {
    if (!opts.silent) {
      process.stderr.write(`${formatSavings(s, { color: wantsColor() })}\n`);
    }
    if (root && opts.recordStats !== false) recordSavings(root, tool, s, sessionStartedAt);
  };
  const savingsNote = (s: Savings) => {
    const { savedTokens, reductionPct } = savingsOf(s);
    return ` original=${s.originalTokens} saved=${savedTokens} (${reductionPct}%)`;
  };

  // ---------------------------------------------------------------------------
  // Root + watcher lifecycle. An explicit root (--root / ROOT env) warms up
  // immediately. Otherwise the server auto-detects: project markers around the
  // cwd win at startup; if none exist, the root is chosen lazily from the first
  // tool call, and later calls re-point the watcher when the active file moves
  // to a different project.
  // ---------------------------------------------------------------------------
  const explicitRoot = opts.root?.trim() || process.env.ROOT?.trim() || '';
  const autoMode = explicitRoot === '';

  let root = '';
  let watcher: WatcherHandle | null = null;
  let searchIndex: SymbolSearch | null = null;
  let lifecycle: Promise<void> = Promise.resolve();

  // `.tokenshrinkrc.json` state: re-read at every root attach and hot-reloaded
  // when the file changes under a running server.
  let config: TokenShrinkConfig = { ...EMPTY_CONFIG };
  let configFsw: fs.FSWatcher | null = null;
  let configReloadTimer: NodeJS.Timeout | null = null;

  const stopConfigWatch = () => {
    if (configReloadTimer) {
      clearTimeout(configReloadTimer);
      configReloadTimer = null;
    }
    if (configFsw) {
      configFsw.close();
      configFsw = null;
    }
  };

  const reloadForRoot = async (r: string) => {
    const next = loadConfig(r, (m) => log(m));
    const changed = JSON.stringify(next) !== JSON.stringify(config);
    config = next;
    if (!changed || !watcher || root !== r) return;
    log('.tokenshrinkrc.json changed — re-indexing with the new rules.');
    stopConfigWatch();
    const old = watcher;
    watcher = null;
    root = '';
    await old.close().catch(() => {});
    await attachWatcher(r, false);
  };

  const startConfigWatch = (r: string) => {
    stopConfigWatch();
    const cfgPath = configPathFor(r);
    if (!fs.existsSync(cfgPath)) return;
    try {
      configFsw = fs.watch(cfgPath, () => {
        if (configReloadTimer) clearTimeout(configReloadTimer);
        configReloadTimer = setTimeout(() => {
          void enqueue(() => reloadForRoot(r));
        }, 200);
      });
    } catch {
      /* fs.watch unavailable — config hot-reload disabled for this root */
    }
  };

  // Auto-create agent integration rules so the tool is used by default.
  const writeRules = (r: string) => {
    if (opts.createRule === false) return;
    for (const target of resolveTargets(opts.ruleTarget)) {
      const res = createAutoRule(r, target);
      if (res.created) {
        log(`Wrote ${target} rule to ${res.filePath}`);
      } else if (res.skipped === 'user') {
        log(`${target} rule exists (user-authored); leaving it untouched.`);
      }
    }
  };

  /**
   * Attach a watcher to `r`. When `waitForIndex` is true the returned promise
   * only resolves once the cold tree index finishes (used on the lazy first
   * call so Ring 1 is already warm).
   */
  const attachWatcher = (r: string, waitForIndex: boolean): Promise<void> => {
    stopConfigWatch();
    config = loadConfig(r, (m) => log(m));
    const search = new SymbolSearch();
    const w = createWatcher({
      root: r,
      ignored: opts.ignored,
      config,
      onIndexed: (abs, entry) => {
        if (entry.symbols && entry.symbols.length > 0) search.setFile(abs, entry.symbols);
        else search.removeFile(abs);
      },
      onRemoved: (abs) => search.removeFile(abs),
    });
    searchIndex = search;
    root = r;
    watcher = w;
    writeRules(r);
    log(`Indexing ${r} in the background…`);
    const indexed = w
      .indexAll()
      .then((n) => log(`Indexed ${n} files.`))
      .catch((err: unknown) => log(`Indexing ${r} failed: ${(err as Error)?.message ?? err}`));
    startConfigWatch(r);
    return waitForIndex ? indexed : Promise.resolve();
  };

  /** Serialize lifecycle transitions so concurrent tool calls cannot race. */
  const enqueue = (fn: () => Promise<void>): Promise<void> => {
    const run = lifecycle.then(fn);
    lifecycle = run.then(
      () => {},
      () => {},
    );
    return run;
  };

  if (explicitRoot) {
    void enqueue(() => attachWatcher(path.resolve(explicitRoot), false));
  } else {
    const fromCwd = detectProjectRoot(process.cwd());
    if (fromCwd) {
      log(`Auto-detected project root ${fromCwd} (from cwd). Pass --root to pin it.`);
      void enqueue(() => attachWatcher(fromCwd, false));
    } else {
      log(
        'No --root and no project markers around the current directory — ' +
          'will auto-detect the project from the first tool call.',
      );
    }
  }

  /**
   * Ensure a watcher covers `activeFilePath`. No-op once ready; in auto mode a
   * file outside the current root triggers detection of a new root.
   */
  const ensureReadyFor = (activeFilePath: string): Promise<void> =>
    enqueue(async () => {
      const abs = path.resolve(activeFilePath);
      if (watcher && root) {
        if (!autoMode || isWithin(root, abs)) return; // already covered
        const next = detectProjectRoot(abs);
        if (!next || next === root) return; // nothing better to index
        log(`Active file is in a different project (${next}); re-indexing (was ${root}).`);
        await watcher.close().catch(() => {});
        watcher = null;
        root = '';
      }
      if (root) return; // defensive: watcher attached meanwhile
      const detected = detectProjectRoot(abs);
      const target = detected ?? process.cwd();
      if (detected) {
        log(`Auto-detected project root ${target} from ${abs}.`);
      } else {
        log(`No project markers around ${abs}; falling back to ${target}.`);
      }
      await attachWatcher(target, true);
    });

  const server = new McpServer(
    { name: 'token-shrink', version: VERSION },
    { capabilities: { tools: {} } },
  );

  server.registerTool(
    'get_compressed_code_context',
    {
      title: 'Get Compressed Code Context',
      description:
        'Returns a compressed, framework-aware AST context payload for one or more files: ' +
        'each active file’s full source (Ring 0) plus pruned skeletons of their direct ' +
        'imports (Ring 1). Implementation bodies are removed but type signatures, ' +
        'interfaces, and module exports are preserved for ~80-90% token reduction. ' +
        'Use `activeFiles` to pin multiple files as Ring 0 and `maxTokens` to cap the ' +
        'payload with a relevance-ranked Ring 1.',
      inputSchema: {
        activeFilePath: z
          .string()
          .optional()
          .describe('Path to the file the agent is working on (or use `activeFiles`)'),
        activeFiles: z
          .array(z.string())
          .optional()
          .describe('Multiple files to keep as Ring 0 (full text); mutually exclusive with `activeFilePath`'),
        maxSkeletons: z
          .number()
          .int()
          .min(1)
          .max(200)
          .optional()
          .describe('Cap on number of dependency skeletons to include'),
        maxTokens: z
          .number()
          .int()
          .positive()
          .optional()
          .describe('Hard token budget for the whole payload; Ring 1 is relevance-ranked and packed to fit'),
        includeStats: z
          .boolean()
          .optional()
          .describe('Append approximate token-count stats'),
      },
    },
    async ({ activeFilePath, activeFiles, maxSkeletons, maxTokens, includeStats }) => {
      const paths = resolveActiveFiles(activeFilePath, activeFiles);
      // In auto-detect mode each Ring-0 file may live in a different project;
      // ensure the watcher covers every one before assembling.
      for (const p of paths) await ensureReadyFor(p);
      if (!watcher) {
        throw new Error('token-shrink watcher failed to start');
      }
      const result = assembleMany(paths, watcher.cache.entries, {
        maxSkeletons,
        maxTokens,
        includeStats,
      });
      const ts = result.tokenStats;
      const budgetNote =
        ts.budget !== undefined ? ` budget=${ts.budget} trimmed=${ts.trimmed}` : '';
      reportSavings('get_compressed_code_context', ts);
      return {
        content: [
          {
            type: 'text' as const,
            text: result.markdown,
          },
          {
            type: 'text' as const,
            text:
              `[stats] files=${result.activeFilePaths.length} ` +
              `dependencies=${result.included.length} unresolved=${result.unresolved.length} ` +
              `tokens=${ts.totalTokens}${savingsNote(ts)}${budgetNote}`,
          },
        ],
      };
    },
  );

  server.registerTool(
    'expand_symbol',
    {
      title: 'Expand Symbol',
      description:
        'Returns the full, un-pruned source of a named definition (function, method, ' +
        'class, interface, enum, arrow/const function, …) from one file. Use it when ' +
        'a Ring-1 skeleton is not enough — e.g. you need the exact algorithm inside ' +
        'a pruned body before writing or changing code.',
      inputSchema: {
        filePath: z.string().describe('Path to the file containing the symbol'),
        symbolName: z
          .string()
          .describe('Name of the definition to expand (exact name preferred; falls back to case-insensitive/substring)'),
        maxMatches: z
          .number()
          .int()
          .min(1)
          .max(20)
          .optional()
          .describe('Maximum matching definitions to return (default 5)'),
      },
    },
    async ({ filePath, symbolName, maxMatches }) => {
      await ensureReadyFor(filePath);
      const abs = path.resolve(filePath);
      let source: string;
      try {
        source = fs.readFileSync(abs, 'utf8');
      } catch {
        return textReply(`File not found or unreadable: ${filePath}`);
      }
      const spec = languageForFile(abs);
      if (!spec) {
        return textReply(`No token-shrink grammar for file type: ${filePath}`);
      }
      const { symbols } = await analyze(abs, source, { skipPrune: true });
      if (symbols.length === 0) {
        return textReply(
          `No parseable definitions found in ${filePath} — the grammar may be unavailable ` +
            '(first run offline) or the language exposes no name-carrying definitions yet.',
        );
      }
      const matches = matchSymbols(symbols, symbolName).slice(0, maxMatches ?? 5);
      if (matches.length === 0) {
        const names = [...new Set(symbols.map((s) => s.name))].slice(0, 12).join(', ');
        return textReply(
          `No symbol named "${symbolName}" in ${filePath}.` +
            (names ? ` Other definitions there: ${names}.` : ''),
        );
      }
      const fence = path.extname(abs).replace(/^\./, '') || 'text';
      const parts = matches.map((m) => {
        const body = source.slice(m.start, m.end).trim();
        return (
          `### ${m.name} (${m.kind}) — ${abs}:${m.line}` +
          '\n\n```' +
          fence +
          '\n' +
          body +
          '\n```\n'
        );
      });
      const disambig =
        matches.length > 1
          ? `\n_Multiple definitions matched (${matches.length}); each is shown above._`
          : '';
      return textReply(parts.join('\n') + disambig);
    },
  );

  server.registerTool(
    'git_diff_context',
    {
      title: 'Git Diff Context',
      description:
        'Builds an impact-analysis payload from git changes: every changed file is ' +
        'kept as Ring 0 (full code), their imports AND the files that import them ' +
        '(file-level callers) are attached as pruned Ring-1 skeletons. Use for PR ' +
        'reviews, regression fixes and multi-file tasks where no single "active file" exists.',
      inputSchema: {
        scope: z
          .enum(['worktree', 'staged', 'branch'])
          .optional()
          .describe("Diff scope: 'worktree' (default, staged+unstaged), 'staged', or 'branch' (base...head)"),
        base: z.string().optional().describe('Base ref for scope=branch (default HEAD~1)'),
        head: z.string().optional().describe('Head ref for scope=branch (default HEAD)'),
        includeUntracked: z
          .boolean()
          .optional()
          .describe('Include untracked files (worktree scope only)'),
        maxFiles: z
          .number()
          .int()
          .min(1)
          .max(200)
          .optional()
          .describe('Maximum changed files to include (default 30)'),
        maxImporters: z
          .number()
          .int()
          .min(0)
          .max(100)
          .optional()
          .describe('Maximum importer skeletons to append (default 20)'),
        maxSkeletons: z
          .number()
          .int()
          .min(1)
          .max(200)
          .optional()
          .describe('Cap on dependency skeletons per payload'),
        maxTokens: z
          .number()
          .int()
          .positive()
          .optional()
          .describe('Hard token budget for the whole payload'),
        includeStats: z.boolean().optional().describe('Append approximate token-count stats'),
      },
    },
    async ({
      scope,
      base,
      head,
      includeUntracked,
      maxFiles,
      maxImporters,
      maxSkeletons,
      maxTokens,
      includeStats,
    }) => {
      // The git root is the server root; in auto mode detect from cwd until a
      // tool call establishes the project.
      await ensureReadyFor(process.cwd());
      if (!watcher || !root) {
        throw new Error('token-shrink watcher failed to start');
      }
      const repoRoot = root;
      const changedResult = await gitChangedFiles(repoRoot, {
        scope: (scope as GitDiffScope) ?? 'worktree',
        base,
        head,
        includeUntracked,
      } satisfies GitChangedOptions);
      if (changedResult.error) {
        return textReply(`git error: ${changedResult.error}`);
      }
      if (changedResult.files.length === 0) {
        return textReply('No changed files (clean worktree, or empty diff for the requested scope).');
      }
      const fileCap = maxFiles ?? 30;
      const changed = changedResult.files.slice(0, fileCap);
      const filesTruncated = changedResult.files.length > changed.length;

      // Warm not-yet-indexed changed files so Ring-1 edges are accurate.
      for (const abs of changed) {
        if (!watcher.cache.entries.has(abs)) {
          try {
            await watcher.index(abs);
          } catch {
            /* unparseable file — skip */
          }
        }
      }

      const assembled = assembleMany(changed, watcher.cache.entries, {
        maxSkeletons,
        maxTokens,
        includeStats,
      });

      // Reverse edges: files that import the changed files (file-level callers).
      const changedSet = new Set(changed);
      const importerOf = new Map<string, string[]>();
      for (const [fileAbs, entry] of watcher.cache.entries) {
        for (const imp of entry.imports) {
          if (!changedSet.has(imp)) continue;
          const list = importerOf.get(imp) ?? [];
          list.push(fileAbs);
          importerOf.set(imp, list);
        }
      }
      const importerList = [...new Set([...importerOf.values()].flat())].filter(
        (f) => !changedSet.has(f),
      );
      const importerCap = maxImporters ?? 20;
      const importers = importerList.slice(0, importerCap);
      const importersTruncated = importerList.length > importers.length;
      let importerTokens = 0;
      let importerOriginalTokens = 0;

      const relLabel = (abs: string) => {
        const rel = path.relative(repoRoot, abs);
        return rel && !rel.startsWith('..') ? rel : abs;
      };
      const fence = (abs: string) => path.extname(abs).replace(/^\./, '') || 'text';

      const parts: string[] = [];
      parts.push(
        `# Git Impact Context (${changed.length} changed file${changed.length === 1 ? '' : 's'})`,
        '',
      );
      parts.push(`- changed files: ${changed.map(relLabel).join(', ')}`);
      if (importers.length > 0) {
        parts.push(`- importing files (callers): ${importers.map(relLabel).join(', ')}`);
      }
      parts.push('', '---', '');
      parts.push('## Changed files — full code', '');
      for (const abs of changed) {
        parts.push(`### \`${relLabel(abs)}\``, '');
        let source = '';
        try {
          source = fs.readFileSync(abs, 'utf8');
        } catch {
          /* file vanished between listing and read */
        }
        parts.push(`\`\`\`${fence(abs)}`, source.trim() || '(unreadable file)', '```', '');
      }
      parts.push(`## Ring 1 — Pruned dependencies (${assembled.included.length})`, '');
      parts.push('', 'Implementation bodies removed; type signatures, interfaces and exports retained.', '');
      if (assembled.included.length === 0) {
        parts.push('_No local dependency skeletons available._', '');
      }
      for (const inc of assembled.included) {
        const entry = watcher.cache.entries.get(inc.filePath);
        const label = relLabel(inc.filePath);
        parts.push(`### \`${label}\``, '');
        if (entry) {
          parts.push(`\`\`\`${fence(inc.filePath)}`, entry.skeleton.trim(), '```', '');
        } else {
          parts.push('_Unindexed file._', '');
        }
        parts.push('');
      }
      if (assembled.tokenStats.budget !== undefined && assembled.tokenStats.trimmed > 0) {
        parts.push(
          `_Note: token budget of ${assembled.tokenStats.budget} excluded ` +
            `${assembled.tokenStats.trimmed} lower-priority dependencies._`,
          '',
        );
      }

      if (importers.length > 0) {
        parts.push(`## Ring 2 — Files importing the diff (${importers.length})`, '');
        for (const abs of importers) {
          const entry = watcher.cache.entries.get(abs);
          if (!entry) continue;
          const cost = approximateTokens(entry.skeleton);
          importerTokens += cost;
          importerOriginalTokens += entry.originalTokens ?? cost;
        }
        parts.push('', 'Pruned skeletons of modules that call into the changed files.', '');
        for (const abs of importers) {
          const entry = watcher.cache.entries.get(abs);
          parts.push(`### \`${relLabel(abs)}\``, '');
          if (entry) {
            parts.push(`\`\`\`${fence(abs)}`, entry.skeleton.trim(), '```', '');
          } else {
            parts.push('_Unindexed file._', '');
          }
          parts.push('');
        }
        if (importersTruncated) {
          parts.push(
            `_…and ${importerList.length - importers.length} more importing files (raise maxImporters)._`,
            '',
          );
        }
      }
      if (filesTruncated) {
        parts.push(
          `_Note: capped to ${fileCap} changed files (${changedResult.files.length} total); ` +
            'raise maxFiles to include more._',
          '',
        );
      }
      if (assembled.unresolved.length > 0) {
        parts.push('## Unresolved imports', '');
        for (const u of assembled.unresolved) parts.push(`- \`${u}\``);
        parts.push('');
      }

      const ts = assembled.tokenStats;
      const budgetNote =
        ts.budget !== undefined ? ` budget=${ts.budget} trimmed=${ts.trimmed}` : '';
      const gitSavings: Savings = {
        originalTokens: ts.originalTokens + importerOriginalTokens,
        totalTokens: ts.totalTokens + importerTokens,
      };
      reportSavings('git_diff_context', gitSavings);
      const stats =
        `[git-stats] files=${changed.length} ring1=${assembled.included.length} ` +
        `importers=${importers.length} unresolved=${assembled.unresolved.length} ` +
        `tokens=${gitSavings.totalTokens}${savingsNote(gitSavings)}${budgetNote}`;
      return {
        content: [
          { type: 'text' as const, text: parts.join('\n') },
          { type: 'text' as const, text: stats },
        ],
      };
    },
  );

  server.registerTool(
    'search_symbol_signatures',
    {
      title: 'Search Symbol Signatures',
      description:
        'Fast, repo-wide lookup of named definitions (functions, methods, classes, ' +
        'interfaces, enums, …). Returns compact `file:line — signature` lines instead ' +
        'of raw search hits. Use it to discover where a symbol lives and what its ' +
        'exact signature is before reading or editing code.',
      inputSchema: {
        query: z
          .string()
          .describe('Search text (matched against symbol names; falls back to signatures)'),
        maxResults: z
          .number()
          .int()
          .min(1)
          .max(100)
          .optional()
          .describe('Maximum results to return (default 10)'),
        kind: z
          .enum(['function', 'method', 'arrow', 'class', 'interface', 'enum', 'type', 'other'])
          .optional()
          .describe('Only return definitions of this kind'),
      },
    },
    async ({ query, maxResults, kind }) => {
      await ensureReadyFor(process.cwd());
      if (!searchIndex) {
        throw new Error('token-shrink symbol index failed to start');
      }
      // Cold lazy build: if the background index has not finished yet, load
      // whatever the cache already holds so the first search still answers.
      if (searchIndex.size === 0 && watcher && watcher.cache.entries.size > 0) {
        searchIndex.loadCache(watcher.cache.entries);
      }
      const hits = searchIndex.search(query, {
        maxResults: maxResults ?? 10,
        kind: kind as SymbolKind | undefined,
      });
      if (hits.length === 0) {
        return textReply(`No symbols match "${query}". Try a different name or kind.`);
      }
      const lines = hits.map((h) => `- \`${h.label}\``);
      return textReply(
        `${lines.join('\n')}\n\n_Found ${hits.length} symbol${hits.length === 1 ? '' : 's'} ` +
          `matching "${query}"._`,
      );
    },
  );

  const transport = new StdioServerTransport();
  await server.connect(transport);
  log('MCP server connected.');
  return server;
}

// Start the server only when run as the MCP binary, not when imported as a
// library. Guard against both the source filenames and the tsup bundles:
// `dist/mcp.cjs` (used by the npm `token-shrink-mcp` bin). `realpathSync`
// resolves the npm bin symlink, so `token-shrink-mcp` -> `dist/mcp.cjs` is
// detected as `mcp.cjs`.
const argv1 = process.argv[1] ? path.basename(process.argv[1]) : '';
let argv1Real = '';
try {
  argv1Real = process.argv[1]
    ? path.basename(fs.realpathSync(process.argv[1]))
    : '';
} catch {
  /* path may not exist yet (tsx/dev runners) — fall back to argv basename */
}
const invokedAsMcp =
  argv1 === 'mcp.js' || argv1 === 'mcp.mjs' ||
  argv1 === 'mcp.cjs' || argv1 === 'mcp.ts' ||
  argv1Real === 'mcp.js' || argv1Real === 'mcp.mjs' ||
  argv1Real === 'mcp.cjs' || argv1Real === 'mcp.ts';
if (invokedAsMcp) {
  const rootArg = (() => {
    const i = process.argv.indexOf('--root');
    if (i !== -1 && process.argv[i + 1]) return process.argv[i + 1];
    const eq = process.argv.find((a) => a.startsWith('--root='));
    if (eq) return eq.slice('--root='.length);
    return undefined;
  })();
  const createRule = !(
    process.env.TOKEN_SHRINK_CREATE_RULE === '0' ||
    process.env.TOKEN_SHRINK_CREATE_RULE === 'false' ||
    process.env.CONTEXT_SHRINK_CREATE_RULE === '0' ||
    process.env.CONTEXT_SHRINK_CREATE_RULE === 'false' ||
    process.argv.includes('--no-create-rule') ||
    (() => {
      const f = process.argv.find((a) => a.startsWith('--create-rule='));
      return f ? f.slice('--create-rule='.length) === 'false' : false;
    })()
  );
  // --rule-target=cursor|claude|cline|all (repeatable / comma-separated), default all.
  const rawTargets = process.argv
    .filter((a) => a.startsWith('--rule-target='))
    .flatMap((a) => a.slice('--rule-target='.length).split(','));
  const ruleTarget: RuleTarget | RuleTarget[] | undefined =
    rawTargets.length > 0 && !rawTargets.includes('all')
      ? ([...new Set(rawTargets)].filter(
          (v): v is RuleTarget => v === 'cursor' || v === 'claude' || v === 'cline',
        ) as RuleTarget[])
      : undefined;
  const recordStats = !(
    process.env.TOKEN_SHRINK_STATS === '0' ||
    process.env.TOKEN_SHRINK_STATS === 'false' ||
    process.argv.includes('--no-stats')
  );
  void startMcpServer({ root: rootArg, createRule, ruleTarget, recordStats }).catch((err) => {
    process.stderr.write(`[token-shrink] MCP server error: ${err.message}\n`);
    process.exitCode = 1;
  });
}
