/** Watcher handle shape returned by `createWatcher`. */
type WatcherHandle = ReturnType<typeof createWatcher>;

/** Supported auto-rule integration targets. */
export type RuleTarget = 'cursor' | 'claude' | 'cline';

/** Agent integration file descriptors written when the auto-rule is on. */
interface RuleTargetSpec {
  relPath: string;
  sentinel: string;
  body: string;
}

export const RULE_TARGET_PATH = {
  cursor: '.cursor/rules/token-shrink.mdc',
  claude: '.claude/rules/token-shrink.md',
  cline: '.clinerules/token-shrink.md',
} as const;

/** Bump when the generated rule bodies gain new tool guidance. */
export const RULE_VERSION = 3;
/** Marker line inside generated rules; its presence means "current version". */
export const RULE_VERSION_MARKER = `# token-shrink rule v${RULE_VERSION}`;

